DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM clase_taller) OR EXISTS (SELECT 1 FROM taller) THEN
        RAISE EXCEPTION 'V9 requiere las tablas taller y clase_taller vacías antes de migrar';
    END IF;
END $$;

-- Los talleres fueron vaciados voluntariamente: restablecer el estado del proyecto.
UPDATE proyecto SET cantidad_talleres_plataforma = 0, ultima_sincronizacion_talleres = NULL;
UPDATE proyecto SET estado = 'PLANIFICADO' WHERE estado = 'EN_CURSO';

DROP TABLE clase_taller;
ALTER TABLE taller DROP CONSTRAINT taller_pkey;
ALTER TABLE taller ADD COLUMN id_taller BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE taller ADD CONSTRAINT pk_taller PRIMARY KEY (id_taller);
ALTER TABLE taller ADD CONSTRAINT uq_taller_id_externo UNIQUE (id_taller_plataforma);
ALTER TABLE taller ADD COLUMN ultima_sincronizacion_evidencias TIMESTAMPTZ;

CREATE TABLE clase_taller (
    id_clase_taller BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_taller BIGINT NOT NULL REFERENCES taller(id_taller) ON DELETE CASCADE,
    id_clase_plataforma BIGINT UNIQUE,
    numero_clase INTEGER NOT NULL CHECK (numero_clase > 0),
    nombre_clase VARCHAR(500),
    nombre_modulo VARCHAR(500),
    estado_clase VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    fecha_realizacion DATE,
    cantidad_participantes INTEGER CHECK (cantidad_participantes IS NULL OR cantidad_participantes >= 0),
    cantidad_evidencias INTEGER NOT NULL DEFAULT 0 CHECK (cantidad_evidencias >= 0),
    fecha_primera_sincronizacion TIMESTAMPTZ NOT NULL,
    fecha_ultima_sincronizacion TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_clase_taller_numero UNIQUE(id_taller, numero_clase),
    CONSTRAINT ck_clase_taller_datos CHECK (
        (fecha_realizacion IS NULL AND cantidad_participantes IS NULL AND cantidad_evidencias = 0)
        OR (fecha_realizacion IS NOT NULL AND cantidad_participantes IS NOT NULL)
    ),
    CONSTRAINT ck_clase_taller_estado CHECK (
        (estado_clase = 'REALIZADA' AND fecha_realizacion IS NOT NULL)
        OR (estado_clase = 'PENDIENTE' AND fecha_realizacion IS NULL)
    )
);
CREATE INDEX idx_clase_taller_taller ON clase_taller(id_taller);

CREATE TABLE evidencia (
    id_evidencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_clase_taller BIGINT NOT NULL REFERENCES clase_taller(id_clase_taller) ON DELETE CASCADE,
    id_archivo_plataforma BIGINT NOT NULL UNIQUE CHECK (id_archivo_plataforma > 0),
    nombre_fisico VARCHAR(500) NOT NULL CHECK (BTRIM(nombre_fisico) <> ''),
    mime_type VARCHAR(120) NOT NULL CHECK (BTRIM(mime_type) <> ''),
    tamanio_bytes BIGINT NOT NULL CHECK (tamanio_bytes >= 0),
    es_util BOOLEAN NOT NULL DEFAULT FALSE,
    es_destacada BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_primera_sincronizacion TIMESTAMPTZ NOT NULL,
    fecha_ultima_sincronizacion TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_evidencia_clase ON evidencia(id_clase_taller);
