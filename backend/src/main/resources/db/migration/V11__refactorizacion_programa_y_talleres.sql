-- V11: programa común, clases por taller y respuestas directas.
-- V10 ya fue aplicada: no cambiar su checksum. Los datos de negocio se vacían antes de V11.
-- Nunca borrar flyway_schema_history.
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM proyecto)
       OR EXISTS (SELECT 1 FROM taller)
       OR EXISTS (SELECT 1 FROM clase_taller)
       OR EXISTS (SELECT 1 FROM pregunta_proyecto)
       OR EXISTS (SELECT 1 FROM encuesta_taller)
       OR EXISTS (SELECT 1 FROM respuesta_encuesta)
       OR EXISTS (SELECT 1 FROM evidencia) THEN
        RAISE EXCEPTION 'V11 requiere las tablas de negocio vacías (incluido proyecto, taller y preguntas)';
    END IF;
END $$;

ALTER TABLE proyecto
    ADD COLUMN programa_sincronizado BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN ultima_sincronizacion_programa TIMESTAMPTZ;

CREATE TABLE programa (
    id_programa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyecto BIGINT NOT NULL REFERENCES proyecto(id_proyecto) ON DELETE CASCADE,
    id_clase_plataforma BIGINT NOT NULL CHECK (id_clase_plataforma > 0),
    numero_clase INTEGER NOT NULL CHECK (numero_clase > 0),
    nombre_clase VARCHAR(500) NOT NULL CHECK (BTRIM(nombre_clase) <> ''),
    nombre_modulo VARCHAR(500) NOT NULL CHECK (BTRIM(nombre_modulo) <> ''),
    fecha_primera_syn TIMESTAMPTZ NOT NULL,
    fecha_ultima_syn TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_programa_proyecto_clase UNIQUE(id_proyecto, id_clase_plataforma),
    CONSTRAINT uq_programa_proyecto_numero UNIQUE(id_proyecto, numero_clase)
);

ALTER TABLE pregunta_proyecto
    DROP CONSTRAINT uq_pregunta_proyecto_externa,
    ADD COLUMN id_programa BIGINT NOT NULL REFERENCES programa(id_programa),
    ADD CONSTRAINT uq_pregunta_programa_externa UNIQUE(id_programa, id_pregunta_plataforma),
    ADD CONSTRAINT uq_pregunta_programa_orden UNIQUE(id_programa, orden);

ALTER TABLE clase_taller
    DROP CONSTRAINT IF EXISTS clase_taller_id_clase_plataforma_key,
    DROP CONSTRAINT IF EXISTS ck_clase_taller_datos,
    DROP COLUMN nombre_clase,
    DROP COLUMN nombre_modulo,
    ADD COLUMN id_programa BIGINT NOT NULL REFERENCES programa(id_programa),
    ALTER COLUMN id_clase_plataforma SET NOT NULL,
    ALTER COLUMN cantidad_participantes SET DEFAULT 0,
    ALTER COLUMN cantidad_participantes SET NOT NULL,
    ADD CONSTRAINT uq_clase_taller_programa UNIQUE (id_taller, id_programa),
    ADD CONSTRAINT ck_clase_taller_datos CHECK (
        (estado_clase = 'PENDIENTE' AND fecha_realizacion IS NULL
            AND cantidad_participantes = 0 AND cantidad_evidencias = 0)
        OR (estado_clase = 'REALIZADA' AND fecha_realizacion IS NOT NULL)
    );
CREATE INDEX idx_clase_taller_programa ON clase_taller(id_programa);

ALTER TABLE respuesta_encuesta
    DROP CONSTRAINT uq_respuesta_encuesta_pregunta,
    DROP COLUMN id_encuesta_taller,
    ADD COLUMN id_clase_taller BIGINT NOT NULL REFERENCES clase_taller(id_clase_taller) ON DELETE CASCADE;
ALTER TABLE respuesta_encuesta RENAME TO respuesta_taller;
ALTER TABLE respuesta_taller RENAME COLUMN id_respuesta_encuesta TO id_respuesta_taller;
ALTER TABLE respuesta_taller
    ADD CONSTRAINT uq_respuesta_taller_pregunta UNIQUE (id_clase_taller, id_pregunta_proyecto);
DROP TABLE encuesta_taller;
DROP INDEX IF EXISTS idx_respuesta_encuesta_encuesta;
CREATE INDEX idx_respuesta_taller_clase ON respuesta_taller(id_clase_taller);
