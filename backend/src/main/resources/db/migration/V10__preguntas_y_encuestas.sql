-- Incremento 2.11: preguntas del proyecto y encuestas por clase.
CREATE TABLE pregunta_proyecto (
    id_pregunta_proyecto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyecto BIGINT NOT NULL REFERENCES proyecto(id_proyecto) ON DELETE CASCADE,
    id_pregunta_plataforma BIGINT NOT NULL CHECK (id_pregunta_plataforma > 0),
    enunciado TEXT NOT NULL CHECK (BTRIM(enunciado) <> ''),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('INTRODUCCION', 'CLASE')),
    orden INTEGER NOT NULL CHECK (orden > 0),
    CONSTRAINT uq_pregunta_proyecto_externa UNIQUE (id_pregunta_plataforma)
);
CREATE INDEX idx_pregunta_proyecto ON pregunta_proyecto(id_proyecto);

CREATE TABLE encuesta_taller (
    id_encuesta_taller BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_clase_taller BIGINT NOT NULL UNIQUE REFERENCES clase_taller(id_clase_taller) ON DELETE CASCADE,
    fecha_primera_sincronizacion TIMESTAMPTZ NOT NULL,
    fecha_ultima_sincronizacion TIMESTAMPTZ NOT NULL
);

CREATE TABLE respuesta_encuesta (
    id_respuesta_encuesta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_encuesta_taller BIGINT NOT NULL REFERENCES encuesta_taller(id_encuesta_taller) ON DELETE CASCADE,
    id_pregunta_proyecto BIGINT NOT NULL REFERENCES pregunta_proyecto(id_pregunta_proyecto),
    valor_respuesta TEXT NOT NULL,
    fecha_primera_sincronizacion TIMESTAMPTZ NOT NULL,
    fecha_ultima_sincronizacion TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_respuesta_encuesta_pregunta UNIQUE(id_encuesta_taller, id_pregunta_proyecto)
);
CREATE INDEX idx_respuesta_encuesta_encuesta ON respuesta_encuesta(id_encuesta_taller);
ALTER TABLE taller ADD COLUMN ultima_sincronizacion_encuestas TIMESTAMPTZ;
