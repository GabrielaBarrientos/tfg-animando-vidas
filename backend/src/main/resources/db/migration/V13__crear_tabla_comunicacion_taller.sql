-- V13: registro interno y seguimiento de comunicaciones con docentes.
-- Migración aditiva: no modifica registros ni tablas de V1 a V12.
CREATE TABLE comunicacion_taller (
    id_comunicacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_taller BIGINT NOT NULL,
    id_usuario_registro BIGINT NOT NULL,
    fecha_contacto DATE NOT NULL,
    canal VARCHAR(20) NOT NULL,
    canal_otro VARCHAR(20),
    motivo VARCHAR(40) NOT NULL,
    motivo_otro VARCHAR(20),
    accion_realizada VARCHAR(20) NOT NULL,
    observaciones TEXT,
    resultado VARCHAR(40) NOT NULL,
    fecha_respuesta_docente DATE,
    respuesta_docente TEXT,
    fecha_compromiso DATE,
    f_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    f_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_comunicacion_taller FOREIGN KEY (id_taller)
        REFERENCES taller(id_taller) ON DELETE RESTRICT,
    CONSTRAINT fk_comunicacion_usuario FOREIGN KEY (id_usuario_registro)
        REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    CONSTRAINT ck_comunicacion_canal CHECK (canal IN ('WHATSAPP','LLAMADA','CORREO','OTRO')),
    CONSTRAINT ck_comunicacion_motivo CHECK (motivo IN ('ATRASO_EN_EL_AVANCE',
        'EVIDENCIAS_PENDIENTES','CONSULTA','OTRO')),
    CONSTRAINT ck_comunicacion_accion CHECK (accion_realizada IN
        ('RECORDATORIO','RECLAMO','SEGUIMIENTO')),
    CONSTRAINT ck_comunicacion_resultado CHECK (resultado IN
        ('ESPERANDO_RESPUESTA','RESPUESTA_SIN_COMPROMISO',
         'COMPROMISO_DE_REGULARIZACION','NO_SE_PUDO_CONTACTAR')),
    CONSTRAINT ck_comunicacion_canal_otro CHECK (
        (canal = 'OTRO' AND canal_otro IS NOT NULL AND BTRIM(canal_otro) <> '')
        OR (canal <> 'OTRO' AND canal_otro IS NULL)),
    CONSTRAINT ck_comunicacion_motivo_otro CHECK (
        (motivo = 'OTRO' AND motivo_otro IS NOT NULL AND BTRIM(motivo_otro) <> '')
        OR (motivo <> 'OTRO' AND motivo_otro IS NULL)),
    CONSTRAINT ck_comunicacion_observaciones CHECK (
        observaciones IS NULL OR CHAR_LENGTH(observaciones) <= 5000),
    CONSTRAINT ck_comunicacion_respuesta_longitud CHECK (
        respuesta_docente IS NULL OR CHAR_LENGTH(respuesta_docente) <= 5000),
    CONSTRAINT ck_comunicacion_respuesta CHECK (
        (fecha_respuesta_docente IS NULL AND respuesta_docente IS NULL)
        OR (fecha_respuesta_docente IS NOT NULL AND respuesta_docente IS NOT NULL
            AND BTRIM(respuesta_docente) <> '')),
    CONSTRAINT ck_comunicacion_fecha_respuesta CHECK (
        fecha_respuesta_docente IS NULL OR fecha_respuesta_docente >= fecha_contacto),
    CONSTRAINT ck_comunicacion_fecha_compromiso CHECK (
        fecha_compromiso IS NULL OR (fecha_compromiso >= fecha_contacto
            AND (fecha_respuesta_docente IS NULL OR fecha_compromiso >= fecha_respuesta_docente))),
    CONSTRAINT ck_comunicacion_resultado_respuesta CHECK (
        resultado NOT IN ('ESPERANDO_RESPUESTA','NO_SE_PUDO_CONTACTAR')
        OR fecha_respuesta_docente IS NULL),
    CONSTRAINT ck_comunicacion_resultado_compromiso CHECK (
        fecha_compromiso IS NULL OR resultado = 'COMPROMISO_DE_REGULARIZACION')
);
CREATE INDEX idx_comunicacion_taller_fecha
    ON comunicacion_taller(id_taller, fecha_contacto DESC, id_comunicacion DESC);
CREATE INDEX idx_comunicacion_usuario ON comunicacion_taller(id_usuario_registro);
